void RestoreDefaults(int page) {
    if (page == kCreditsPage) return;
    // the sticks' calibration and the keys are the player's own; everything else goes back
    game::Options keep = game::Opt();
    Get() = DefaultSettings();
    game::Options& o = game::Opt();
    o.keys = keep.keys;
    o.left_deadzone = keep.left_deadzone;
    o.right_deadzone = keep.right_deadzone;
    o.left_sensitivity = keep.left_sensitivity;
    o.right_sensitivity = keep.right_sensitivity;
    Changed();
}

int g_page = kGraphicsPage;

void ValueRow(const Row& r) {
    int step = OptionRow(r.label, Ui(RowText(r.id, 0)).c_str());
    if (step) RowText(r.id, step);
}

void DrawList(const Row* list, size_t count) {
    for (size_t i = 0; i < count; i++) {
        const Row& r = list[i];
        if (r.kind == Kind::Heading) Section(r.label);
        else ValueRow(r);
    }
}

void DrawRows(int page) {
    if (page == kCreditsPage) {
        DrawList(CreditRows().data(), CreditRows().size());
        return;
    }
    size_t count = 0;
    const Row* list = rows::Page(page, &count);
    DrawList(list, count);
}

void Defaults() { RestoreDefaults(g_page); }

// the page's name with an arrow each side to step through the pages
void DrawTitle() {
    float em = ImGui::GetFontSize();
    std::string name = Ui(kPageNames[g_page]);
    ImGui::PushID("page");
    float arrows = em * 2.4f;
    float w = arrows * 2 + em + ImGui::CalcTextSize(name.c_str()).x;
    float x = ImGui::GetCursorPosX() + (ImGui::GetContentRegionAvail().x - w) * 0.5f;
    ImGui::SetCursorPosX(x);
    if (ImGui::ArrowButton("##prev", ImGuiDir_Left)) g_page = StepIndex(g_page, -1, kPages);
    ImGui::SameLine(0, em * 0.5f);
    ImGui::AlignTextToFramePadding();
    ImGui::TextUnformatted(name.c_str());
    ImGui::SameLine(0, em * 0.5f);
    if (ImGui::ArrowButton("##next", ImGuiDir_Right)) g_page = StepIndex(g_page, 1, kPages);
    ImGui::PopID();
}

